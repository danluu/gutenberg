#!/usr/bin/env bash
set -euo pipefail

NODE_BIN=/media/volume/danluu-fuzz-data/rtc-e2e-setup-20260514/.local/node-v20.19.0-linux-x64/bin
TMUX_WRAP=/media/volume/danluu-fuzz-data/rtc-tmux-core-wrapper/bin
SYSTEM_PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
REPO=/media/volume/danluu-fuzz-data/rtc-fuzz-validation-20260515/repo
BASE=/media/volume/danluu-fuzz-data/rtc-coverage-guided-20260515
BUDGET_ENV=${RTC_RESOURCE_BUDGET_ENV:-/media/volume/danluu-fuzz-data/rtc-resource-autoscaler-20260516/current-budget.env}

positive_integer_or_default() {
	local value=$1
	local fallback=$2
	case "$value" in
		''|*[!0-9]*)
			printf '%s\n' "$fallback"
			return
			;;
	esac
	if [ "$value" -gt 0 ]; then
		printf '%s\n' "$value"
	else
		printf '%s\n' "$fallback"
	fi
}

if [ -f "$BUDGET_ENV" ]; then
	# Keep watchdog restarts on the same budget contract as direct coverage starts.
	# shellcheck disable=SC1090
	. "$BUDGET_ENV"
fi
NOVELTY_ALLOW_FLEET_STARTUP_NOISE_CANARY=${RTC_FUZZ_NOVELTY_ALLOW_FLEET_STARTUP_NOISE_CANARY:-0}
NOVELTY_FLEET_STARTUP_NOISE_CANARY_GROUP=${RTC_FUZZ_NOVELTY_FLEET_STARTUP_NOISE_CANARY_GROUP:-novelty-ws-media-cross-entity}
NOVELTY_ALLOW_EMPTY_MATERIALIZATION_NO_PRODUCT_STARTUP_CANARY=${RTC_FUZZ_NOVELTY_ALLOW_EMPTY_MATERIALIZATION_NO_PRODUCT_STARTUP_CANARY:-0}
NOVELTY_MIN_ENABLED_BROWSER_LANES=${RTC_FUZZ_NOVELTY_MIN_ENABLED_BROWSER_LANES:-}
NOVELTY_TARGET_ENABLED_GROUPS=${RTC_FUZZ_NOVELTY_TARGET_ENABLED_GROUPS:-}
NOVELTY_MAX_ENABLED_GROUPS=${RTC_FUZZ_NOVELTY_MAX_ENABLED_GROUPS:-}
NOVELTY_COVERAGE_GUIDED_TARGET_ENABLED_GROUPS=${RTC_FUZZ_NOVELTY_COVERAGE_GUIDED_TARGET_ENABLED_GROUPS:-}
NOVELTY_COVERAGE_GUIDED_MAX_ENABLED_GROUPS=${RTC_FUZZ_NOVELTY_COVERAGE_GUIDED_MAX_ENABLED_GROUPS:-}
NOVELTY_COVERAGE_QUALITY_MAX_ENABLED_GROUPS=${RTC_FUZZ_NOVELTY_COVERAGE_QUALITY_MAX_ENABLED_GROUPS:-}
NOVELTY_DEADLINE_COVERAGE_GAP_RESERVED_GROUPS=${RTC_FUZZ_NOVELTY_DEADLINE_COVERAGE_GAP_RESERVED_GROUPS:-0}
NOVELTY_DEADLINE_BENCHMARK_CANARY_BUDGET_CAP=${RTC_FUZZ_NOVELTY_DEADLINE_BENCHMARK_CANARY_BUDGET_CAP:-0}
NOVELTY_DEADLINE_BENCHMARK_CANARY_BOOTSTRAP_ONLY=${RTC_FUZZ_NOVELTY_DEADLINE_BENCHMARK_CANARY_BOOTSTRAP_ONLY:-}
if [ -z "$NOVELTY_DEADLINE_BENCHMARK_CANARY_BOOTSTRAP_ONLY" ]; then
	if [ "$NOVELTY_DEADLINE_BENCHMARK_CANARY_BUDGET_CAP" = "1" ]; then
		NOVELTY_DEADLINE_BENCHMARK_CANARY_BOOTSTRAP_ONLY=1
	else
		NOVELTY_DEADLINE_BENCHMARK_CANARY_BOOTSTRAP_ONLY=0
	fi
fi
NOVELTY_SUCCESS_DEFICIT_BOOTSTRAP_SLOTS=${RTC_FUZZ_NOVELTY_SUCCESS_DEFICIT_BOOTSTRAP_SLOTS:-}
NOVELTY_SUCCESS_DEFICIT_BOOTSTRAP_SLOTS=$(positive_integer_or_default "$NOVELTY_SUCCESS_DEFICIT_BOOTSTRAP_SLOTS" 2)
NOVELTY_BENCHMARK_CANARY_BOOTSTRAP_RESERVE_SLOTS=${RTC_FUZZ_NOVELTY_BENCHMARK_CANARY_BOOTSTRAP_RESERVE_SLOTS:-}
NOVELTY_BENCHMARK_CANARY_WS_BACKFILL_SLOTS=${RTC_FUZZ_NOVELTY_BENCHMARK_CANARY_WS_BACKFILL_SLOTS:-1}
NOVELTY_BENCHMARK_CANARY_STICKY_GROUP_LIMIT=${RTC_FUZZ_NOVELTY_BENCHMARK_CANARY_STICKY_GROUP_LIMIT:-}
NOVELTY_ZERO_COVERAGE_BOOTSTRAP_SLOTS=${RTC_FUZZ_NOVELTY_ZERO_COVERAGE_BOOTSTRAP_SLOTS:-}
NOVELTY_BENCHMARK_CANARY_SLOT_FLOOR=${RTC_FUZZ_NOVELTY_BENCHMARK_CANARY_SLOT_FLOOR:-}
NOVELTY_BENCHMARK_CANARY_STRICT_SLOT_FLOOR=${RTC_FUZZ_NOVELTY_BENCHMARK_CANARY_STRICT_SLOT_FLOOR:-}
NOVELTY_ALLOW_DISABLED_POLICY_GUARDS=${RTC_FUZZ_NOVELTY_ALLOW_DISABLED_POLICY_GUARDS:-0}
NOVELTY_PAUSE_ON_TRIAGE_NOISE=${RTC_FUZZ_NOVELTY_PAUSE_ON_TRIAGE_NOISE:-1}
mkdir -p "$BASE/logs" "$TMUX_WRAP"
cat > "$TMUX_WRAP/tmux" <<'SH'
#!/usr/bin/env bash
set -euo pipefail
socket=${RTC_TMUX_SOCKET:-rtc-fuzz}
case "${1:-}" in
	capture-pane)
		if [ "$socket" = rtc-fuzz ]; then
			printf 'capture-pane is disabled on the RTC core tmux socket\n' >&2
			exit 1
		fi
		exec flock -w 30 "/tmp/rtc-tmux-${UID}-${socket}.client.lock" /usr/bin/tmux -L "$socket" "$@"
		;;
	display-message|has-session|list-*|show-*)
		exec flock -w 30 "/tmp/rtc-tmux-${UID}-${socket}.client.lock" /usr/bin/tmux -L "$socket" "$@"
		;;
esac
exec /usr/bin/tmux -L "$socket" "$@"
SH
chmod +x "$TMUX_WRAP/tmux"
export PATH="$TMUX_WRAP:$NODE_BIN:$PATH:$SYSTEM_PATH"

tmux kill-session -t rtc-coverage-guided-watchdog 2>/dev/null || true
RECOVER_COMMAND="bin/rtc-jetstream-guard-remote.sh reattach-coverage-once || RTC_COVERAGE_FORCE_RESTART=0 RTC_COVERAGE_CLEANUP_KEEP_WATCHDOG=1 RTC_RESOURCE_BUDGET_ENV=$BUDGET_ENV RTC_FUZZ_NOVELTY_ALLOW_FLEET_STARTUP_NOISE_CANARY=$NOVELTY_ALLOW_FLEET_STARTUP_NOISE_CANARY RTC_FUZZ_NOVELTY_FLEET_STARTUP_NOISE_CANARY_GROUP=$NOVELTY_FLEET_STARTUP_NOISE_CANARY_GROUP RTC_FUZZ_NOVELTY_ALLOW_EMPTY_MATERIALIZATION_NO_PRODUCT_STARTUP_CANARY=$NOVELTY_ALLOW_EMPTY_MATERIALIZATION_NO_PRODUCT_STARTUP_CANARY RTC_FUZZ_NOVELTY_ALLOW_DISABLED_POLICY_GUARDS=$NOVELTY_ALLOW_DISABLED_POLICY_GUARDS RTC_FUZZ_NOVELTY_PAUSE_ON_TRIAGE_NOISE=$NOVELTY_PAUSE_ON_TRIAGE_NOISE RTC_FUZZ_NOVELTY_MIN_ENABLED_BROWSER_LANES=$NOVELTY_MIN_ENABLED_BROWSER_LANES RTC_FUZZ_NOVELTY_TARGET_ENABLED_GROUPS=$NOVELTY_TARGET_ENABLED_GROUPS RTC_FUZZ_NOVELTY_MAX_ENABLED_GROUPS=$NOVELTY_MAX_ENABLED_GROUPS RTC_FUZZ_NOVELTY_COVERAGE_GUIDED_TARGET_ENABLED_GROUPS=$NOVELTY_COVERAGE_GUIDED_TARGET_ENABLED_GROUPS RTC_FUZZ_NOVELTY_COVERAGE_GUIDED_MAX_ENABLED_GROUPS=$NOVELTY_COVERAGE_GUIDED_MAX_ENABLED_GROUPS RTC_FUZZ_NOVELTY_COVERAGE_QUALITY_MAX_ENABLED_GROUPS=$NOVELTY_COVERAGE_QUALITY_MAX_ENABLED_GROUPS RTC_FUZZ_NOVELTY_DEADLINE_COVERAGE_GAP_RESERVED_GROUPS=$NOVELTY_DEADLINE_COVERAGE_GAP_RESERVED_GROUPS RTC_FUZZ_NOVELTY_DEADLINE_BENCHMARK_CANARY_BUDGET_CAP=$NOVELTY_DEADLINE_BENCHMARK_CANARY_BUDGET_CAP RTC_FUZZ_NOVELTY_DEADLINE_BENCHMARK_CANARY_BOOTSTRAP_ONLY=$NOVELTY_DEADLINE_BENCHMARK_CANARY_BOOTSTRAP_ONLY RTC_FUZZ_NOVELTY_SUCCESS_DEFICIT_BOOTSTRAP_SLOTS=$NOVELTY_SUCCESS_DEFICIT_BOOTSTRAP_SLOTS RTC_FUZZ_NOVELTY_BENCHMARK_CANARY_BOOTSTRAP_RESERVE_SLOTS=$NOVELTY_BENCHMARK_CANARY_BOOTSTRAP_RESERVE_SLOTS RTC_FUZZ_NOVELTY_BENCHMARK_CANARY_WS_BACKFILL_SLOTS=$NOVELTY_BENCHMARK_CANARY_WS_BACKFILL_SLOTS RTC_FUZZ_NOVELTY_BENCHMARK_CANARY_STICKY_GROUP_LIMIT=$NOVELTY_BENCHMARK_CANARY_STICKY_GROUP_LIMIT RTC_FUZZ_NOVELTY_ZERO_COVERAGE_BOOTSTRAP_SLOTS=$NOVELTY_ZERO_COVERAGE_BOOTSTRAP_SLOTS RTC_FUZZ_NOVELTY_BENCHMARK_CANARY_SLOT_FLOOR=$NOVELTY_BENCHMARK_CANARY_SLOT_FLOOR RTC_FUZZ_NOVELTY_BENCHMARK_CANARY_STRICT_SLOT_FLOOR=$NOVELTY_BENCHMARK_CANARY_STRICT_SLOT_FLOOR bin/rtc-coverage-guided-start-remote.sh"
COMMAND="unset RTC_COVERAGE_FORCE_RESTART; cd '$REPO'; export PATH='$TMUX_WRAP':'$NODE_BIN':\$PATH:'$SYSTEM_PATH' CI=1 RTC_FUZZ_SESSION_WATCHDOG_REPO_ROOT='$REPO' RTC_FUZZ_SESSION_WATCHDOG_SESSION='rtc-coverage-guided-novelty' RTC_FUZZ_SESSION_WATCHDOG_BASE_DIR='$BASE' RTC_FUZZ_SESSION_WATCHDOG_CURRENT_OUTPUT_FILE='$BASE/current-output-dir.txt' RTC_FUZZ_SESSION_WATCHDOG_STATE_RELATIVE_PATH='novelty-state.json' RTC_FUZZ_SESSION_WATCHDOG_STATUS_RELATIVE_PATH='novelty-status.md' RTC_FUZZ_SESSION_WATCHDOG_START_COMMAND='$RECOVER_COMMAND' RTC_FUZZ_SESSION_WATCHDOG_POLL_MS=60000 RTC_FUZZ_SESSION_WATCHDOG_STALE_MS=900000 RTC_FUZZ_SESSION_WATCHDOG_START_GRACE_MS=900000 RTC_FUZZ_SESSION_WATCHDOG_MIN_RESTART_INTERVAL_MS=900000; node bin/rtc-browser-fuzz-session-watchdog.mjs >> '$BASE/logs/session-watchdog-tmux.log' 2>&1"
tmux new-session -d -s rtc-coverage-guided-watchdog "bash -lc \"$COMMAND\""
tmux ls | grep -E 'rtc-coverage-guided|rtc-fuzz-strict|strict-expansion-watchdog' || true
